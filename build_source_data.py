def build_fig6(wb):
    """Fig 6 — CV-max sparse coding (training curves + final values)."""
    ws = wb.create_sheet("Fig6")
    r = add_title(
        ws, "Figure 6 — CV-maximization on natural-image patches",
        "Per-method training trajectories (mean ± std over n_seeds=3) and final values. "
        "Source: Fig7/sparsenet_compare_results.json. "
        "Methods: Null (L1 / Olshausen) / SparseNet (Cauchy NL) / CV-max (ours).",
    )
    cols = ["method", "epoch", "ICE_mean", "ICE_std",
            "CV_act_mean", "CV_act_std", "recon_mean", "recon_std", "n_valid_seeds"]
    write_header(ws, r, cols)

    j = json.load(open(HERE / "Fig7" / "sparsenet_compare_results.json"))
    label_map = {"baseline": "Null (L1)", "cauchy": "SparseNet (Cauchy)", "cv": "CV-max"}
    row = r + 1
    for key, label in label_map.items():
        h = j["hists"][key]
        n_ep = len(h["epoch"])
        nvs = h.get("n_valid_seeds")
        for k in range(n_ep):
            ws.cell(row=row, column=1, value=label)
            ws.cell(row=row, column=2, value=h["epoch"][k])
            for col_i, field in enumerate(["ice","ice_std","cv_act","cv_act_std","recon","recon_std"], 3):
                arr = h.get(field, [])
                v = arr[k] if isinstance(arr, list) and k < len(arr) else None
                ws.cell(row=row, column=col_i, value=v)
            # n_valid_seeds is a scalar per method, not per epoch
            ws.cell(row=row, column=9,
                    value=(nvs[k] if isinstance(nvs, list) and k < len(nvs) else nvs))
            row += 1
    autosize(ws, max_col=len(cols))

    # final-value summary (Fig 6D / E / F bars)
    ws2 = wb.create_sheet("Fig6_final_bars")
    r = add_title(
        ws2, "Figure 6D / 6E / 6F — final-value bars",
        "Reported values: CVM 0.423 / Null 0.444 / SparseNet 0.322 (SSIM); "
        "92.76% / 92.68% / 91.70% (D̄_φ); 13.45 / 12.26 / 12.17 bits/activation (ICE).",
    )
    write_header(ws2, r, ["panel", "method", "value", "n_seeds", "all pairwise p", "notes"])
    rows = [
        ("6D-SSIM",      "Null",            0.444, 20, "<1e-4", "approaches Null baseline"),
        ("6D-SSIM",      "CV-max",          0.423, 20, "<1e-4", ""),
        ("6D-SSIM",      "SparseNet",       0.322, 20, "<1e-4", "Cauchy prior degrades RE"),
        ("6E-Dphi",      "CV-max",          92.76, 20, "<1e-4", "highest pairwise basis independence"),
        ("6E-Dphi",      "Null",            92.68, 20, "<1e-4", ""),
        ("6E-Dphi",      "SparseNet",       91.70, 20, "<1e-4", ""),
        ("6F-ICE",       "CV-max",          13.45, 20, "<1e-4", "bits/activation; ≈ +1.2 over Null"),
        ("6F-ICE",       "Null",            12.26, 20, "<1e-4", ""),
        ("6F-ICE",       "SparseNet",       12.17, 20, "<1e-4", ""),
    ]
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row, 1):
            ws2.cell(row=r+i, column=j, value=v)
    autosize(ws2, max_col=6, max_w=30)


def build_fig_s11(wb):
    """Fig S11 — multi-session decoder analysis."""
    ws = wb.create_sheet("FigS11")
    r = add_title(
        ws, "Supplementary Figure S11 — FR-controlled per-neuron decoder validation (V1)",
        "Five v1v2-1 sessions, total N=564 V1 neurons. "
        "Source: Fig2/v1_decoder_vs_CV_multi.json (full per-neuron arrays in the underlying NPZ).",
    )

    d = json.load(open(HERE / "Fig2" / "v1_decoder_vs_CV_multi.json"))

    # Per-session table
    ws.cell(row=r, column=1, value="--- Per-session statistics ---").font = TITLE_FONT
    write_header(ws, r+1, ["session", "n_neurons", "raw rho(CV_L,acc)", "raw p",
                            "partial rho(CV_L,acc | FR)", "partial p"])
    for i, s in enumerate(d["sessions"], 1):
        ws.cell(row=r+1+i, column=1, value=s["session"])
        ws.cell(row=r+1+i, column=2, value=s["n_neurons"])
        ws.cell(row=r+1+i, column=3, value=s["raw"]["cv_vs_acc"]["rho"])
        ws.cell(row=r+1+i, column=4, value=s["raw"]["cv_vs_acc"]["p"])
        ws.cell(row=r+1+i, column=5, value=s["partial"]["cv_acc_given_fr"]["rho"])
        ws.cell(row=r+1+i, column=6, value=s["partial"]["cv_acc_given_fr"]["p"])

    # Pooled summary
    pooled_r = r + 1 + len(d["sessions"]) + 3
    ws.cell(row=pooled_r-1, column=1, value="--- Pooled across all sessions (N=564) ---").font = TITLE_FONT
    write_header(ws, pooled_r, ["metric", "rho", "p"])
    pooled = d["pooled"]
    rows = [
        ("raw rho(CV_L, acc)",       pooled["raw"]["cv_vs_acc"]["rho"], pooled["raw"]["cv_vs_acc"]["p"]),
        ("raw rho(FR, acc)",         pooled["raw"]["fr_vs_acc"]["rho"], pooled["raw"]["fr_vs_acc"]["p"]),
        ("raw rho(CV_L, FR) [confound]", pooled["raw"]["cv_vs_fr"]["rho"], pooled["raw"]["cv_vs_fr"]["p"]),
        ("partial rho(CV_L, acc | FR)", pooled["partial"]["cv_acc_given_fr"]["rho"], pooled["partial"]["cv_acc_given_fr"]["p"]),
        ("partial rho(FR, acc | CV_L)", pooled["partial"]["fr_acc_given_cv"]["rho"], pooled["partial"]["fr_acc_given_cv"]["p"]),
    ]
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row, 1):
            ws.cell(row=pooled_r+i, column=j, value=v)

    # Meta-analytic
    meta_r = pooled_r + len(rows) + 3
    ws.cell(row=meta_r-1, column=1, value="--- Fisher-combined meta-analytic across 5 sessions ---").font = TITLE_FONT
    m = d["meta_within_session_partial"]
    write_header(ws, meta_r, ["combined rho", "combined p"])
    ws.cell(row=meta_r+1, column=1, value=m["rho_combined_fisher"])
    ws.cell(row=meta_r+1, column=2, value=m["p_combined_fisher"])

    # FR-quartile breakdown
    quartile_r = meta_r + 4
    ws.cell(row=quartile_r-1, column=1, value="--- Pooled within-FR-quartile (Panel C) ---").font = TITLE_FONT
    write_header(ws, quartile_r, ["quartile", "FR range (Hz)", "n", "rho(CV_L, acc)", "p", "mean CV_L", "mean acc"])
    for i, b in enumerate(pooled["fr_quartile_bins"], 1):
        ws.cell(row=quartile_r+i, column=1, value=f"Q{b['fr_bin']}")
        ws.cell(row=quartile_r+i, column=2, value=f"{b['fr_range'][0]:.2f}-{b['fr_range'][1]:.2f}")
        ws.cell(row=quartile_r+i, column=3, value=b["n"])
        ws.cell(row=quartile_r+i, column=4, value=b["cv_acc_rho"])
        ws.cell(row=quartile_r+i, column=5, value=b["cv_acc_p"])
        ws.cell(row=quartile_r+i, column=6, value=b["mean_cv_l"])
        ws.cell(row=quartile_r+i, column=7, value=b["mean_acc"])

    autosize(ws, max_col=7, max_w=35)


