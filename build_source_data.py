"""
build_source_data.py
====================
Build the Nature Communications Source Data Excel file.

One sheet per main-text figure (and the supplementary figures for which
we have machine-readable data), populated from:
  - Fig2/Fig2_panels_CD_CVL_data.npz           (V1 per-neuron CV_L, S_L, FR)
  - Fig2/fig2_stats.csv                         (V1 spon/evk summary stats)
  - Fig2/v1_decoder_vs_CV_multi.json            (5-session decoder, Fig S11)
  - Fig7/sparsenet_compare_results.json         (CV-max vs Null vs SparseNet)

Sheets without machine-readable input (Fig 3 single-neuron, Fig 4
recurrent network, Fig 5 cross-system frontier, Fig 6 CVM/Null/SparseNet
bar values) are written as schemas with column headers and short
instructions, so the user can drop their MATLAB exports into them.

Outputs: SourceData.xlsx in the repository root.
"""
from __future__ import annotations
import json
from pathlib import Path

import numpy as np
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter

HERE = Path(__file__).resolve().parent
OUT  = HERE / "SourceData.xlsx"

# --- styling helpers ------------------------------------------------------

HEADER_FONT = Font(bold=True, color="FFFFFF")
HEADER_FILL = PatternFill("solid", fgColor="2C3E50")
NOTE_FONT   = Font(italic=True, color="555555")
TITLE_FONT  = Font(bold=True, size=12)


def write_header(ws, row, cols):
    for j, c in enumerate(cols, 1):
        cell = ws.cell(row=row, column=j, value=c)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center")


def autosize(ws, max_col=10, min_w=12, max_w=30):
    for j in range(1, max_col + 1):
        col = get_column_letter(j)
        max_len = min_w
        for cell in ws[col]:
            if cell.value is not None:
                max_len = max(max_len, min(max_w, len(str(cell.value))))
        ws.column_dimensions[col].width = max_len + 2


def add_title(ws, title, subtitle=None):
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    if subtitle:
        ws["A2"] = subtitle
        ws["A2"].font = NOTE_FONT
        return 4
    return 3


# --- sheet builders -------------------------------------------------------

def build_fig1(wb):
    """Fig 1C — theoretical curves (parametric; no empirical data)."""
    ws = wb.create_sheet("Fig1")
    r = add_title(
        ws, "Figure 1C — Theoretical ICE–CV manifold under bounded linear cost",
        "Curves are evaluated analytically from Supp. Eqs. 8–13 for a dense grid "
        "of the dimensionless tightness parameter k = β·r_max.",
    )
    write_header(ws, r, ["k = β·r_max", "CV", "ICE (bits/nat)", "marginal β"])
    ws.cell(row=r+1, column=1, value="Generated by Fig1/Fig1c.py — re-run to regenerate.")
    ws.cell(row=r+1, column=1).font = NOTE_FONT
    autosize(ws)


def build_fig2(wb):
    """Fig 2C, 2D — V1 per-neuron CV_L, S_L, mean firing rate."""
    ws = wb.create_sheet("Fig2")
    r = add_title(
        ws, "Figure 2 — Macaque V1 lifetime CV and sparseness (per-neuron)",
        "Each row is one V1 neuron (N=159). Spontaneous and evoked values paired across the same neurons. "
        "Dataset: CRCNS v1v2-1, session 105l001p16. Used in panels C (S_L vs FR, CV_L vs FR) and D (S_L vs CV_L).",
    )
    npz = np.load(HERE / "Fig2" / "Fig2_panels_CD_CVL_data.npz", allow_pickle=True)
    cols = ["neuron_id",
            "FR_spon_Hz", "CV_L_spon", "S_L_spon",
            "FR_evk_Hz",  "CV_L_evk",  "S_L_evk"]
    write_header(ws, r, cols)
    n = len(npz["mu_spon"])
    for i in range(n):
        ws.cell(row=r+1+i, column=1, value=i+1)
        ws.cell(row=r+1+i, column=2, value=float(npz["mu_spon"][i]))
        ws.cell(row=r+1+i, column=3, value=float(npz["cvL_spon"][i]))
        ws.cell(row=r+1+i, column=4, value=float(npz["sL_spon"][i]))
        ws.cell(row=r+1+i, column=5, value=float(npz["mu_evk"][i]))
        ws.cell(row=r+1+i, column=6, value=float(npz["cvL_evk"][i]))
        ws.cell(row=r+1+i, column=7, value=float(npz["sL_evk"][i]))
    autosize(ws, max_col=len(cols))

    # --- Fig 2 inset summary stats ------------------------------------
    ws2 = wb.create_sheet("Fig2_stats_summary")
    r = add_title(
        ws2, "Figure 2C insets — paired spontaneous-vs-evoked summary statistics",
        "Per-trial population statistics (N=3200 trials per condition). "
        "Source: Fig2/fig2_stats.csv. Reproduces the *** significance markers in Fig. 2C insets.",
    )
    import csv
    with open(HERE / "Fig2" / "fig2_stats.csv") as fh:
        rdr = list(csv.reader(fh))
    header = rdr[0]
    write_header(ws2, r, header)
    for i, row in enumerate(rdr[1:], 1):
        for j, v in enumerate(row, 1):
            try:
                ws2.cell(row=r+i, column=j, value=float(v))
            except ValueError:
                ws2.cell(row=r+i, column=j, value=v)
    autosize(ws2, max_col=len(header))


