# --- driver ---------------------------------------------------------------

def main():
    wb = openpyxl.Workbook()
    # remove default empty sheet
    wb.remove(wb.active)

    build_readme(wb)
    build_fig1(wb)
    build_fig2(wb)
    build_fig3_placeholder(wb)
    build_fig4_placeholder(wb)
    build_fig5_placeholder(wb)
    build_fig6(wb)
    build_fig_s11(wb)

    wb.save(OUT)
    print(f"[ok] wrote {OUT}  ({OUT.stat().st_size/1024:.1f} kB)")


if __name__ == "__main__":
    main()
